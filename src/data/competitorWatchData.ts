export function getOfficialKPIs(
  watchList: CompetitorWatchListItem[] = ALL_COMPETITOR_WATCHLIST,
  signals: CompetitorSignalCardItem[] = VERIFIED_COMPETITOR_SIGNALS
): CompetitorKPIs {
  const safeWatchList = Array.isArray(watchList) ? watchList : ALL_COMPETITOR_WATCHLIST;
  const safeSignals = Array.isArray(signals) ? signals : VERIFIED_COMPETITOR_SIGNALS;
  const watchCount = safeWatchList.length;
  const priceChangeCount = safeSignals.filter(
    (s) => s?.changeType === 'PRICE DOWN' || s?.changeType === 'PRICE UP'
  ).length;
  const newPromotionCount = safeSignals.filter(
    (s) => s?.changeType === 'NEW PROMOTION' || s?.changeType === 'HOTEL'
  ).length;
  const newPackageCount = safeSignals.filter(
    (s) => s?.changeType === 'NEW PACKAGE' || s?.changeType === 'PACKAGE' || s?.changeType === 'WELLNESS' || s?.changeType === 'SPA'
  ).length;
  const newPartnershipCount = safeSignals.filter(
    (s) => s?.changeType === 'NEW PARTNERSHIP' || s?.changeType === 'PARTNERSHIP'
  ).length;
  const notableCompetitorCount = safeSignals.filter((s) => s?.isImportant || s?.isTopSignal).length;

  return {
    watchCount,
    priceChangeCount,
    newPromotionCount,
    newPackageCount,
    newPartnershipCount,
    notableCompetitorCount,
  };
}
